export function rollCollectionItem(kind, random = Math.random) {
  const pool =
    kind === "pet" ? PETS : kind === "decoration" ? DECORATIONS : COSMETICS;
  let choice =
    random() *
    pool.reduce((sum, item) => sum + RARITIES[item.rarity].weight, 0);
  for (const item of pool) {
    choice -= RARITIES[item.rarity].weight;
    if (choice < 0) return item;
  }
  return pool.at(-1);
}
